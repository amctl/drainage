-- Add a separate pothole dataset; existing drainage demo rows remain untouched.
create table public.pothole_reports (
  id bigint generated by default as identity primary key,
  description text not null check (char_length(description) between 3 and 500),
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  photo_path text check (photo_path is null or photo_path like user_id::text || '/%'),
  status text not null default 'pending' check (status in ('pending', 'active', 'fixed')),
  user_id uuid not null default auth.uid(),
  created_at timestamptz not null default now(),
  last_checked_at timestamptz,
  next_check_at timestamptz default now() + interval '7 days',
  current_check_cycle integer not null default 0 check (current_check_cycle >= 0),
  next_check_cycle integer not null default 1 check (next_check_cycle > 0),
  reminder_count integer not null default 0 check (reminder_count between 0 and 8),
  resolved_at timestamptz
);

create table public.pothole_responses (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.pothole_reports(id) on delete cascade,
  user_id uuid not null default auth.uid(),
  cycle integer not null default 0 check (cycle >= 0),
  response text not null check (response in ('exists', 'fixed', 'cannot_find')),
  created_at timestamptz not null default now(),
  unique (report_id, user_id, cycle),
  check (cycle > 0 or response <> 'fixed')
);

create table public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid(),
  endpoint text not null unique check (endpoint ~ '^https://'),
  p256dh text not null,
  auth text not null,
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  active boolean not null default true,
  opted_in_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.pothole_reports enable row level security;
alter table public.pothole_responses enable row level security;
alter table public.push_subscriptions enable row level security;

