-- The public view never exposes reporter ids. Endpoint/key records are only
-- readable by the owner or service role and are never part of a public view.
create view public.pothole_summaries with (security_barrier = true) as
select r.id, r.description, r.lat, r.lng, (r.photo_path is not null) as has_photo, r.status, r.created_at,
       r.last_checked_at, r.next_check_at, r.current_check_cycle, r.next_check_cycle, r.resolved_at,
       coalesce((select count(*)::integer from public.pothole_responses x
                 where x.report_id = r.id and x.cycle = 0 and x.response = 'exists'), 0) as confirmation_count,
       coalesce((select count(*)::integer from public.pothole_responses x
                 where x.report_id = r.id and x.cycle = 0 and x.response = 'cannot_find'), 0) as cannot_find_count,
       coalesce((select count(*)::integer from public.pothole_responses x
                 where x.report_id = r.id and x.cycle = r.current_check_cycle and x.response = 'exists'), 0) as still_here_count,
       coalesce((select count(*)::integer from public.pothole_responses x
                 where x.report_id = r.id and x.cycle = r.current_check_cycle and x.response = 'fixed'), 0) as fixed_this_checkin_count,
       coalesce((select count(*)::integer from public.pothole_responses x
                 where x.report_id = r.id and x.cycle > 0 and x.response = 'fixed'), 0) as fixed_response_count
from public.pothole_reports r;

create or replace function public.refresh_pothole_status()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  yes_count integer;
  gone_count integer;
  still_count integer;
begin
  if new.cycle = 0 then
    select count(*) filter (where response = 'exists')::integer
      into yes_count from public.pothole_responses where report_id = new.report_id and cycle = 0;
    if yes_count >= 2 then
      update public.pothole_reports set status = 'active' where id = new.report_id and status = 'pending';
    end if;
  else
    select count(*) filter (where response = 'fixed')::integer,
           count(*) filter (where response = 'exists')::integer
      into gone_count, still_count from public.pothole_responses
      where report_id = new.report_id and cycle = new.cycle;
    if still_count > 0 then
      update public.pothole_reports set status = 'active', resolved_at = null,
             next_check_at = now() + interval '7 days'
        where id = new.report_id and status = 'fixed';
    elsif gone_count >= 2 then
      update public.pothole_reports set status = 'fixed', resolved_at = now(), next_check_at = null
        where id = new.report_id and status <> 'fixed';
    else
      update public.pothole_reports set last_checked_at = now()
        where id = new.report_id and status <> 'fixed';
    end if;
  end if;
  return new;
end;
$$;

create or replace function public.validate_pothole_response_cycle()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  report_status text;
  active_cycle integer;
begin
  select status, current_check_cycle into report_status, active_cycle
    from public.pothole_reports where id = new.report_id for update;
  if not found then raise exception 'Pothole report not found.'; end if;
  if new.cycle = 0 and report_status <> 'pending' then
    raise exception 'Initial confirmation is closed for this report.';
  elsif new.cycle > 0 and (new.cycle <> active_cycle
    or (report_status <> 'active' and not (report_status = 'fixed' and new.response = 'exists'))) then
    raise exception 'This check-in cycle is no longer open.';
  end if;
  return new;
end;
$$;

create trigger pothole_response_cycle_guard
  before insert or update of response, cycle on public.pothole_responses
  for each row execute function public.validate_pothole_response_cycle();

create trigger pothole_response_updates_status
  after insert or update of response on public.pothole_responses
  for each row execute function public.refresh_pothole_status();

-- Durable outbox for scheduled check-ins. A scheduler retry can safely pick up
-- pending jobs without advancing the same report cycle twice.
create table public.pothole_followup_jobs (
  report_id bigint not null references public.pothole_reports(id) on delete cascade,
  cycle integer not null check (cycle > 0),
  created_at timestamptz not null default now(),
  attempts integer not null default 0,
  available_at timestamptz not null default now(),
  lease_until timestamptz,
  delivered_at timestamptz,
  primary key (report_id, cycle)
);
alter table public.pothole_followup_jobs enable row level security;

create or replace function public.enqueue_due_pothole_followups(batch_size integer default 100)
returns integer language plpgsql security definer set search_path = public as $$
declare
  item public.pothole_reports%rowtype;
  queued integer := 0;
begin
  for item in
    select * from public.pothole_reports
    where status = 'active' and next_check_at <= now() and reminder_count < 8
    order by next_check_at
    for update skip locked
    limit greatest(1, least(batch_size, 500))
  loop
    insert into public.pothole_followup_jobs (report_id, cycle)
      values (item.id, item.next_check_cycle) on conflict do nothing;
    if found then
      update public.pothole_reports
        set current_check_cycle = item.next_check_cycle,
            next_check_cycle = item.next_check_cycle + 1,
            reminder_count = reminder_count + 1,
            next_check_at = case when reminder_count + 1 >= 8 then null else now() + interval '7 days' end
        where id = item.id;
      queued := queued + 1;
    end if;
  end loop;

  -- Stop reminders after the cap, even if an old due timestamp remains.
  update public.pothole_reports set next_check_at = null
    where status = 'active' and reminder_count >= 8 and next_check_at is not null;
  return queued;
end;
$$;

create or replace function public.lease_pothole_followup_jobs(batch_size integer default 100)
returns table (report_id bigint, cycle integer, user_id uuid, description text, lat double precision, lng double precision)
language plpgsql security definer set search_path = public as $$
begin
  return query
    with picked as (
      select j.report_id, j.cycle
      from public.pothole_followup_jobs j
      join public.pothole_reports r on r.id = j.report_id and r.status = 'active'
      where j.delivered_at is null and j.available_at <= now()
        and (j.lease_until is null or j.lease_until < now()) and j.attempts < 6
      order by j.available_at
      for update of j skip locked
      limit greatest(1, least(batch_size, 100))
    ), leased as (
      update public.pothole_followup_jobs j
      set attempts = j.attempts + 1, lease_until = now() + interval '5 minutes'
      from picked p where j.report_id = p.report_id and j.cycle = p.cycle
      returning j.report_id, j.cycle
    )
    select l.report_id, l.cycle, r.user_id, r.description, r.lat, r.lng
    from leased l join public.pothole_reports r on r.id = l.report_id
    where r.status = 'active';
end;
$$;

create or replace function public.complete_pothole_followup_job(job_report_id bigint, job_cycle integer, delivery_succeeded boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
  update public.pothole_followup_jobs
  set delivered_at = case when delivery_succeeded then now() else null end,
      available_at = case when delivery_succeeded then available_at else now() + interval '15 minutes' end,
      lease_until = null
  where report_id = job_report_id and cycle = job_cycle and delivered_at is null;
end;
$$;

